import type { Metadata } from "next";
import { Suspense } from "react";
import { Alert, Badge, ButtonLink, Card, EmptyState, LoadingBlock, PageHeader, Skeleton } from "@/components/ui/primitives";
import { getDataProvider } from "@/lib/data";
import { formatDate } from "@/lib/format";

export const metadata: Metadata = { title: "Insights" };

const TONE_BADGE = { good: { tone: "good", icon: "✓", label: "Looks healthy" }, warn: { tone: "warn", icon: "!", label: "Worth a look" }, info: { tone: "info", icon: "ℹ", label: "Good to know" } } as const;

async function InsightsContent() {
  const report = await getDataProvider().getInsights();
  if (report.items.length === 0) {
    return (
      <EmptyState
        title="Not enough data for insights"
        description="Connect a bank with transactions to see sample insights."
        action={<ButtonLink href="/connect">Connect an institution</ButtonLink>}
      />
    );
  }
  return (
    <div className="space-y-6">
      {report.source === "sample-rules" ? (
        <Alert tone="demo" title="Sample insights, not AI analysis">
          <p>
            These are generated by fixed, transparent rules from your demo data as of {formatDate(report.snapshotDate)}. AI-powered analysis with NVIDIA
            Nemotron will replace them once the Capital Insight backend provides it. Nothing here is financial advice.
          </p>
        </Alert>
      ) : null}
      <ul className="grid grid-cols-1 gap-4 lg:grid-cols-2">
        {report.items.map((insight) => {
          const badge = TONE_BADGE[insight.tone];
          return (
            <li key={insight.id}>
              <Card as="article" headingLevel={2} className="h-full" title={insight.title} action={<Badge tone={badge.tone}><span aria-hidden="true">{badge.icon}</span> {badge.label}</Badge>}>
                {insight.metric ? (
                  <p className="mb-2">
                    <span className="text-2xl font-semibold tabular-nums">{insight.metric.value}</span>{" "}
                    <span className="text-sm text-muted">{insight.metric.label}</span>
                  </p>
                ) : null}
                <p className="text-sm">{insight.body}</p>
                <details className="mt-3 text-xs text-muted">
                  <summary className="cursor-pointer font-medium text-primary">How this was calculated</summary>
                  <ul className="mt-1 list-disc pl-4">
                    {insight.basis.map((line) => (
                      <li key={line}>{line}</li>
                    ))}
                  </ul>
                </details>
              </Card>
            </li>
          );
        })}
      </ul>
    </div>
  );
}

export default function InsightsPage() {
  return (
    <>
      <PageHeader title="Insights" description="Observations about your spending, cash cushion and debt." />
      <Suspense
        fallback={
          <LoadingBlock label="Loading insights">
            <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
              {[0, 1, 2, 3].map((key) => (
                <Skeleton key={key} className="h-44" />
              ))}
            </div>
          </LoadingBlock>
        }
      >
        <InsightsContent />
      </Suspense>
    </>
  );
}
